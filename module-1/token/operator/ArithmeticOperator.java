class ArithmeticOperator {
    public static void main(String[] args) {
         int a = 10;
         int b = 5;
         
         System.out.println("Addition of "+a+" and "+b+" is: " + (a + b)); // Addition
         System.out.println("Subtraction of "+a+" and "+b+" is: " + (a - b)); // Subtraction
         System.out.println("Multiplication of "+a+" and "+b+" is: " + (a * b)); // Multiplication
         System.out.println("Division of "+a+" and "+b+" is: " + (a / b)); // Division
         System.out.println("Modulus of "+a+" and "+b+" is: " + (a % b)); // Modulus
     }
 }